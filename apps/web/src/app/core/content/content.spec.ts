import { describe, expect, it } from 'vitest';
import { caseStudies } from './case-studies';
import { profile } from './profile';
import {
  openSourceGroups,
  openSourceTotal,
  openSourceUpdatedAt,
} from './open-source.generated';

/**
 * These tests guard the content, not the code. A missing description or a
 * duplicated slug is the kind of mistake that ships silently, so it fails the
 * build instead.
 */

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

describe('case studies', () => {
  it('has at least one', () => {
    expect(caseStudies.length).toBeGreaterThan(0);
  });

  it('has unique, url-safe slugs', () => {
    const slugs = caseStudies.map((c) => c.slug);
    expect(new Set(slugs).size).toBe(slugs.length);
    for (const slug of slugs) {
      expect(slug, `"${slug}" is not a clean slug`).toMatch(SLUG);
    }
  });

  it('fills in every field the page renders', () => {
    for (const study of caseStudies) {
      expect(study.title.trim(), study.slug).not.toBe('');
      expect(study.summary.trim(), study.slug).not.toBe('');
      expect(study.body.trim(), study.slug).not.toBe('');
      expect(study.stack.length, study.slug).toBeGreaterThan(0);
    }
  });
});

describe('open source (generated by tools/fetch-prs.mjs)', () => {
  it('has the three repositories, each kept separate', () => {
    expect(openSourceGroups.map((g) => g.repo)).toEqual([
      'angular/angular',
      'angular/angular-cli',
      'angular/components',
    ]);
  });

  it('totals the merged counts across the groups', () => {
    const summed = openSourceGroups.reduce((n, g) => n + g.merged, 0);
    expect(openSourceTotal).toBe(summed);
    expect(openSourceTotal).toBeGreaterThan(0);
  });

  it('lists real pull requests under the right repository', () => {
    for (const group of openSourceGroups) {
      expect(group.prs.length, group.repo).toBeGreaterThan(0);
      for (const pr of group.prs) {
        expect(pr.url, pr.title).toContain(`https://github.com/${group.repo}/pull/`);
        expect(pr.number, pr.title).toBeGreaterThan(0);
        expect(pr.mergedAt, pr.title).toMatch(ISO_DATE);
        expect(pr.title.trim()).not.toBe('');
      }
    }
  });

  it('lists each group newest first', () => {
    for (const group of openSourceGroups) {
      const dates = group.prs.map((p) => Date.parse(p.mergedAt));
      expect(dates, group.repo).toEqual([...dates].sort((a, b) => b - a));
    }
  });

  it('records when it was refreshed', () => {
    expect(openSourceUpdatedAt).toMatch(ISO_DATE);
  });
});

describe('profile', () => {
  it('has contact details the page can use', () => {
    expect(profile.email).toContain('@');
    expect(profile.name.trim()).not.toBe('');
    expect(profile.specialism.trim()).not.toBe('');
  });
});
