/**
 * Fetches merged pull requests from GitHub and writes them into the app as a
 * typed TypeScript file.
 *
 * Runs at BUILD time, never in a visitor's browser. The site stays static, no
 * one waits on GitHub to read the page, and GitHub's rate limits can never
 * affect a visitor.
 *
 * If GitHub is unreachable the script keeps the file that is already committed
 * and exits successfully, so a GitHub outage can never fail a deploy.
 *
 *   node tools/fetch-prs.mjs
 */
import { writeFileSync, existsSync } from 'node:fs';

const AUTHOR = 'MeAkib';

/** Shown as three separate groups, in this order. */
const REPOS = [
  { repo: 'angular/angular', label: 'Angular', blurb: 'The framework itself — documentation, accessibility and developer experience.' },
  { repo: 'angular/angular-cli', label: 'Angular CLI', blurb: 'The build and tooling side: the CLI, schematics and the build system.' },
  { repo: 'angular/components', label: 'Angular Components', blurb: 'Material and the CDK — component behaviour and accessibility.' },
];

/** How many recent PRs to list under each group. */
const SHOW = 6;

const OUT = 'apps/web/src/app/core/content/open-source.generated.ts';

async function search(repo) {
  const q = `is:pr author:${AUTHOR} is:merged repo:${repo}`;
  const url =
    'https://api.github.com/search/issues?q=' +
    encodeURIComponent(q) +
    `&sort=created&order=desc&per_page=${SHOW * 3}`;

  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': AUTHOR + '-portfolio' };
  // optional: lifts the rate limit, never required
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${repo}: HTTP ${res.status}`);

  const json = await res.json();

  // GitHub's search sorts by when a PR was opened. We show when it was
  // MERGED, and those orders differ — a PR opened in March can merge after
  // one opened in April. So over-fetch, re-sort by merge date, then trim.
  const prs = (json.items ?? [])
    .map((i) => ({
      number: i.number,
      title: i.title,
      url: i.html_url,
      mergedAt: (i.pull_request?.merged_at ?? i.closed_at ?? '').slice(0, 10),
    }))
    .filter((p) => p.mergedAt)
    .sort((a, b) => b.mergedAt.localeCompare(a.mergedAt))
    .slice(0, SHOW);

  return { total: json.total_count, prs };
}

function render(groups, total) {
  const stamp = new Date().toISOString().slice(0, 10);
  return `// GENERATED by tools/fetch-prs.mjs on ${stamp}. Do not edit by hand.
import { OpenSourceGroup } from '../models';

/** Merged pull requests across all tracked repositories. */
export const openSourceTotal = ${total};

export const openSourceGroups: OpenSourceGroup[] = ${JSON.stringify(groups, null, 2)};

/** The day this list was last refreshed, so the page can be honest about it. */
export const openSourceUpdatedAt = '${stamp}';
`;
}

try {
  const groups = [];
  let total = 0;

  for (const meta of REPOS) {
    const { total: count, prs } = await search(meta.repo);
    total += count;
    groups.push({ repo: meta.repo, label: meta.label, blurb: meta.blurb, merged: count, prs });
    console.log(`  ${meta.repo}: ${count} merged`);
    // the search API is rate limited; be polite between calls
    await new Promise((r) => setTimeout(r, 2000));
  }

  writeFileSync(OUT, render(groups, total));
  console.log(`  wrote ${OUT} — ${total} merged pull requests in total`);
} catch (err) {
  console.warn(`  GitHub fetch failed (${err.message}).`);
  if (existsSync(OUT)) {
    console.warn('  Keeping the committed list so the build still succeeds.');
  } else {
    console.error('  No committed list to fall back on.');
    process.exit(1);
  }
}
